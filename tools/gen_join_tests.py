# Writes test/join_cases.inc from ircdocs/parser-tests msg-join.yaml: a small
# reader for that file's shape (desc, atoms: tags, source, verb, params;
# matches) -- the lines a message of those atoms may be written as.
import json, re, sys
src, out = sys.argv[1], sys.argv[2]

def yaml_double(t):
    res, i = [], 0
    simple = {"\\": "\\", '"': '"', "n": "\n", "t": "\t", "r": "\r", "0": "\0", "e": "\x1b", "a": "\x07", "/": "/", " ": " "}
    while i < len(t):
        ch = t[i]
        if ch != "\\": res.append(ch); i += 1; continue
        n = t[i + 1]
        if n in simple: res.append(simple[n]); i += 2
        elif n == "x": res.append(chr(int(t[i+2:i+4], 16))); i += 4
        elif n == "u": res.append(chr(int(t[i+2:i+6], 16))); i += 6
        else: res.append(n); i += 2
    return "".join(res)

def value(v):
    v = v.strip()
    if v.startswith('"'): return yaml_double(v[1:-1])
    if v.startswith("'"): return v[1:-1].replace("''", "'")
    return v

cases, cur, section = [], None, None
for raw in open(src, encoding="utf-8"):
    line = raw.rstrip("\n")
    if not line.strip() or line.strip().startswith("#"): continue
    m = re.match(r"^  - desc: (.*)$", line)
    if m:
        cur = {"desc": value(m.group(1)), "tags": [], "source": None, "verb": "", "params": [], "matches": []}
        cases.append(cur); section = None; continue
    if cur is None: continue
    s = line.strip()
    if s == "atoms:": continue
    if s == "tags:": section = "tags"; continue
    if s == "params:": section = "params"; continue
    if s == "matches:": section = "matches"; continue
    m = re.match(r"^(source|verb): (.*)$", s)
    if m:
        cur[m.group(1)] = value(m.group(2)); section = None; continue
    if s.startswith("- ") and section in ("params", "matches"):
        cur[section].append(value(s[2:])); continue
    if section == "tags":
        m = re.match(r'^("(?:[^"\\]|\\.)*"|[^:]+):\s*(.*)$', s)
        k, v = value(m.group(1)), m.group(2)
        cur["tags"].append((k, value(v) if v else ""))

def lit(s):
    b = s.encode("utf-8")
    body = "".join(chr(c) if 32 <= c < 127 and chr(c) not in '"\\' else "\\x%02x\"\"" % c for c in b)
    return 'std::string_view("%s", %d)' % (body, len(b))

rows = []
for c in cases:
    rows.append("  {%s, {%s}, %s, %s, {%s}, {%s}}," % (
        json.dumps(c["desc"]),
        ", ".join("{%s, %s}" % (lit(k), lit(v)) for k, v in c["tags"]),
        lit(c["source"]) if c["source"] is not None else "std::nullopt",
        lit(c["verb"]),
        ", ".join(lit(p) for p in c["params"]),
        ", ".join(lit(m) for m in c["matches"])))
open(out, "w").write("// Generated by tools/gen_join_tests.py from ircdocs/parser-tests msg-join.yaml (CC0).\n" + "\n".join(rows) + "\n")
print(len(rows))
